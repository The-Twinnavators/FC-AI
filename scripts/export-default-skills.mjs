// Exports skills from a running FlowCode into packages/daemon/src/knowledge/defaultSkills.ts, so every new install
// starts with them. Usage (daemon running):  node scripts/export-default-skills.mjs [port]
// Exports: skills FlowCode proposed and you turned on (skill.proposed-*), skills you made yourself, and your own
// version of a built-in when it's yours (source "user"). Each ships as a built-in, so later FlowCode versions can
// improve it; a copy someone edits in their library is never replaced.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const port = process.argv[2] ?? "7457";
const auth = { headers: { authorization: "Bearer dev-token-flowcode" } };
const res = await fetch(`http://127.0.0.1:${port}/skills`, auth);
let skills = await res.json();
skills = skills.items ?? skills;
const today = new Date().toISOString().slice(0, 10);

const picked = skills
  .filter((s) => s.source === "user" && s.enabled !== false)
  .map((s) => {
    // A built-in you replaced with your own version (e.g. a longer frontend-design): ships as its next version.
    const builtinId = !s.id.startsWith("skill.proposed-") && s.id !== "skill.responsive-tables";
    const version = builtinId ? "1.1.0" : s.version;
    const note = builtinId ? "The owner's expanded version, shipped as the default" : "Shipped as a default skill (from the owner's library)";
    const { source, ...rest } = s;
    return { ...rest, version, source: "builtin", changelog: [...(s.changelog ?? []), { version, date: today, note }] };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const out = `/**
 * Default skills every new install starts with, beyond the core built-ins (skills.ts, skillLibrary.ts): the skills
 * FlowCode proposed from failures that kept happening (on for every step: they were needed), skills the owner added,
 * and the owner's expanded version of a built-in. Generated by scripts/export-default-skills.mjs; edit there or
 * re-export rather than by hand. They load like built-ins: a newer version replaces a stored copy, never one edited
 * in the library.
 */
import type { SkillSpec } from "@flowcode/contracts";

export const DEFAULT_SKILLS: SkillSpec[] = ${JSON.stringify(picked, null, 2)} as SkillSpec[];
`;
const file = path.join(root, "packages/daemon/src/knowledge/defaultSkills.ts");
fs.writeFileSync(file, out);
console.log(`Wrote ${picked.length} skills to ${path.relative(root, file)}:`);
for (const s of picked) console.log(`  ${s.id} v${s.version}`);
